// Bake the vendored OFL font files into base64 JavaScript so the shipped HTML stays
// a single offline file. The browser registers these bytes with FontFace at boot.
// This mirrors jacquard-index's font bake: the source font is never fetched at run
// time, and the checked-in license remains beside the checked-in font data.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const OUT = resolve(ROOT, 'src/render/fontData.js');

const fonts = [
  {
    id: 'DISPLAY',
    family: 'Popinjay Rye',
    file: 'vendor/fonts/Rye-Regular.ttf',
    weight: '400',
    license: 'vendor/fonts/OFL-Rye.txt',
  },
  {
    id: 'BODY_REGULAR',
    family: 'Popinjay Old Standard',
    file: 'vendor/fonts/OldStandard-Regular.ttf',
    weight: '400',
    license: 'vendor/fonts/OFL-OldStandard.txt',
  },
  {
    id: 'BODY_BOLD',
    family: 'Popinjay Old Standard',
    file: 'vendor/fonts/OldStandard-Bold.ttf',
    weight: '700',
    license: 'vendor/fonts/OFL-OldStandard.txt',
  },
];

const lines = [
  '// AUTO-GENERATED by scripts/bake-font-data.mjs — do not hand-edit.',
  '// Sources and SIL OFL 1.1 license texts are checked in under vendor/fonts/.',
  '',
  "export const DISPLAY_FONT_FAMILY = 'Popinjay Rye';",
  "export const BODY_FONT_FAMILY = 'Popinjay Old Standard';",
  '',
];

for (const font of fonts) {
  const abs = resolve(ROOT, font.file);
  const b64 = readFileSync(abs).toString('base64');
  lines.push(`// ${font.file} — license: ${font.license}`);
  lines.push(`const ${font.id}_FONT_BASE64 = '${b64}';`);
  lines.push('');
}

lines.push(`export async function registerTypography() {
  if (typeof FontFace === 'undefined' || typeof document === 'undefined' || !document.fonts) return false;
  const specs = [
    [DISPLAY_FONT_FAMILY, DISPLAY_FONT_BASE64, '400'],
    [BODY_FONT_FAMILY, BODY_REGULAR_FONT_BASE64, '400'],
    [BODY_FONT_FAMILY, BODY_BOLD_FONT_BASE64, '700'],
  ];
  const faces = specs.map(([family, data, weight]) => new FontFace(
    family,
    \`url(data:font/ttf;base64,\${data}) format("truetype")\`,
    { style: 'normal', weight, display: 'block' },
  ));
  await Promise.all(faces.map((face) => face.load()));
  for (const face of faces) document.fonts.add(face);
  await document.fonts.ready;
  return true;
}
`);

writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${relative(ROOT, OUT)} (${(readFileSync(OUT).length / 1024).toFixed(1)} KB)`);
