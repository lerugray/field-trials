// The hero portrait pool, in stable order — the stranger's face is one of these,
// picked seeded at creation (M10 A10). HERO stays index 0 (the default/fallback).
export const HERO_PORTRAITS = ['HERO', 'HERO_CAP', 'HERO_HORN', 'HERO_TALL'];

// Deterministically choose a hero portrait id from an integer seed.
export function heroPortraitFor(seed) {
  const i = (seed >>> 0) % HERO_PORTRAITS.length;
  return HERO_PORTRAITS[i];
}

