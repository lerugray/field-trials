// Compile all busts to { id -> int[20][20] } using the tileart parser at 20px.
export function createBusts(raw = RAW_BUSTS) {
  const busts = {};
  for (const id of Object.keys(raw)) busts[id] = parseArt(id, raw[id], BUST_SIZE);
  return {
    ids: () => Object.keys(busts),
    get: (id) => {
      const g = busts[id];
      if (!g) throw new Error(`busts.get: unknown bust '${id}'`);
      return g;
    },
    has: (id) => Object.prototype.hasOwnProperty.call(busts, id),
  };
}

// Map a being (or its id) to a bust art id; falls back to HERO for the party.
export function bustArtId(being) {
  const id = typeof being === 'string' ? being : (being && being.id);
  return id || 'HERO';
}

