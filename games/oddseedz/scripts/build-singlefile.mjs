// build-singlefile — emits the shipped single-file game plus the Pages share
// wrapper. The game is a zero-dependency, file://-friendly artifact at
// dist/game/index.html. The wrapper at dist/index.html is the deployed root:
// it frames /game/ and fails loudly if that path ever 404s again.
//
// Strategy: read index.html, find its <script type="module" src="..."> entry,
// walk the relative-import graph, strip import/export syntax, topologically
// concatenate every module into ONE inline module script, and inline it back
// into the HTML. Our modules use only named imports/exports with unique
// top-level names, so a single shared module scope is safe.

import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const IMPORT_RE = /^\s*import\s+[^;]*?from\s*['"]([^'"]+)['"]\s*;?\s*$/gm;

function collectDeps(src) {
  const deps = [];
  let m;
  IMPORT_RE.lastIndex = 0;
  while ((m = IMPORT_RE.exec(src)) !== null) deps.push(m[1]);
  return deps;
}

function stripModuleSyntax(src) {
  return src
    // drop relative import lines
    .replace(IMPORT_RE, '')
    // `export { a, b };` -> gone
    .replace(/^\s*export\s*\{[^}]*\}\s*;?\s*$/gm, '')
    // `export default ` -> (none expected, but be safe)
    .replace(/^\s*export\s+default\s+/gm, '')
    // `export const/let/var/function/class/async` -> strip the keyword
    .replace(/^(\s*)export\s+(?=(async\s+)?(function|const|let|var|class)\b)/gm, '$1');
}

async function buildGraph(entryAbs) {
  const modules = new Map(); // abs path -> { src, deps: [absPath] }
  const order = [];
  const visiting = new Set();

  async function visit(abs) {
    if (modules.has(abs)) return;
    if (visiting.has(abs)) throw new Error('import cycle at ' + abs);
    visiting.add(abs);
    const src = await readFile(abs, 'utf8');
    const depSpecs = collectDeps(src);
    const depAbs = [];
    for (const spec of depSpecs) {
      if (!spec.startsWith('.')) {
        throw new Error(`non-relative import "${spec}" in ${abs} — bundler only handles local modules`);
      }
      const childAbs = resolve(dirname(abs), spec);
      depAbs.push(childAbs);
      await visit(childAbs);
    }
    visiting.delete(abs);
    modules.set(abs, { src, deps: depAbs });
    order.push(abs); // post-order: deps land before dependents
  }

  await visit(entryAbs);
  return { modules, order };
}

async function main() {
  const htmlPath = resolve(ROOT, 'index.html');
  const html = await readFile(htmlPath, 'utf8');

  const tag = html.match(/<script\s+type="module"\s+src="([^"]+)"><\/script>/);
  if (!tag) throw new Error('could not find <script type="module" src="..."> entry in index.html');
  const entryAbs = resolve(ROOT, tag[1]);

  const { modules, order } = await buildGraph(entryAbs);

  const banner = '/* ODDSEEDZ single-file bundle — generated by scripts/build-singlefile.mjs. Do not edit by hand. */';
  const chunks = [banner];
  for (const abs of order) {
    const rel = abs.replace(ROOT + '/', '');
    chunks.push(`\n// ===== ${rel} =====\n` + stripModuleSyntax(modules.get(abs).src).trim());
  }
  const bundled = chunks.join('\n');

  const inlineScript = `<script type="module">\n${bundled}\n</script>`;
  const outHtml = html.replace(tag[0], inlineScript);

  // sanity: the artifact must be self-contained
  const leaks = [];
  if (/\ssrc\s*=\s*["'][^"']+["']/.test(outHtml)) leaks.push('a src= reference remains');
  if (/\shref\s*=\s*["']https?:/.test(outHtml)) leaks.push('an external href remains');
  if (/^\s*import\s+[^;]*?from/m.test(bundled)) leaks.push('an unresolved import remains');
  if (/https?:\/\//.test(bundled)) leaks.push('a URL remains in the bundle');
  if (leaks.length) throw new Error('build not self-contained: ' + leaks.join('; '));

  // Parse the concatenated bundle. All modules share ONE scope after inlining,
  // so a top-level name declared in two modules is a redeclaration SyntaxError.
  // Compiling here (no execution) catches that at build time instead of as a
  // white-screen in the browser. (This guards the "unique top-level names"
  // assumption the whole single-scope strategy rests on.)
  try {
    new vm.Script(bundled, { filename: 'dist-bundle.js' });
  } catch (err) {
    throw new Error(`bundle does not parse (often a duplicate top-level name across modules): ${err.message}`);
  }

  await mkdir(resolve(ROOT, 'dist'), { recursive: true });
  await mkdir(resolve(ROOT, 'dist/game'), { recursive: true });

  const gamePath = resolve(ROOT, 'dist/game/index.html');
  await writeFile(gamePath, outHtml, 'utf8');

  const wrapperPath = resolve(ROOT, 'dist/index.html');
  const wrapperSource = resolve(ROOT, 'public/index.html');
  await copyFile(wrapperSource, wrapperPath);

  const kb = (Buffer.byteLength(outHtml) / 1024).toFixed(1);
  console.log(`built dist/game/index.html (${kb} kB, ${modules.size} modules inlined)`);
  console.log(`built dist/index.html (wrapper from ${wrapperSource.replace(ROOT + '/', '')})`);
}

main().catch((err) => {
  console.error('build failed:', err.message);
  process.exit(1);
});
