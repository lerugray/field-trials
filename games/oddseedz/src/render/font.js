// A code-drawn bitmap font — the single highest-leverage item of the M9 register
// (directive item 6). Chunky, slightly condensed, no thin strokes, in the Monster
// Rancher / Dragon Seeds spirit. Every glyph is authored here as a pixel grid and
// rendered to canvas by filling one square per lit pixel; there is no webfont and
// no system-font UI text once the UI paints through drawText().
//
// Cell geometry: 5 wide x 8 tall. Uppercase / digits occupy rows 0-6 (7 tall) with
// the baseline at the bottom of row 6; lowercase x-height sits in rows 2-6 with
// ascenders reaching row 0 and descenders dropping into row 7. Advance is the glyph
// width plus a 1px tracking gap, all multiplied by the render scale.

