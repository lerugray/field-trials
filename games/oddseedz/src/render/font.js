// Aliases: fold look-alike codepoints onto an authored glyph.
const ALIAS = {
  '↑': '▲',
  '↓': '▼',
  '✕': '×',
  '✗': '×',
  '‘': "'",
  '’': "'",
  '“': '"',
  '”': '"',
  '–': '-',
  '—': '-',
};

const NOTDEF = ['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####', '.....'];

// Parse a raw grid into the list of lit [col,row] pixels once at load.
function parse(grid) {
  const px = [];
  for (let r = 0; r < grid.length; r++) {
    const row = grid[r];
    for (let c = 0; c < row.length; c++) {
      if (row[c] === '#') px.push([c, r]);
    }
  }
  return px;
}

const GLYPHS = {};
for (const [ch, grid] of Object.entries(GLYPH_RAW)) GLYPHS[ch] = parse(grid);

// Resolve a character to its lit-pixel list (via alias), or the .notdef box.
function glyphFor(ch) {
  if (GLYPHS[ch]) return GLYPHS[ch];
  const aliased = ALIAS[ch];
  if (aliased && GLYPHS[aliased]) return GLYPHS[aliased];
  return NOTDEF_PX;
}
const NOTDEF_PX = parse(NOTDEF);

// True iff `ch` has an authored glyph (alias counts).
export function hasGlyph(ch) {
  return Boolean(GLYPHS[ch] || (ALIAS[ch] && GLYPHS[ALIAS[ch]]));
}

// Every directly-authored character (no aliases), for coverage checks + the atlas.
export const SUPPORTED = Object.keys(GLYPH_RAW);

// Width in pixels of `str` at `scale` (glyphs + interior tracking, no trailing gap).
export function measure(str, { scale = 1, tracking = TRACKING } = {}) {
  const n = [...String(str)].length;
  if (n === 0) return { width: 0, height: GLYPH_H * scale };
  const advance = (GLYPH_W + tracking) * scale;
  return { width: n * advance - tracking * scale, height: GLYPH_H * scale };
}

// Draw `str` at (x, y) — the top-left of the first glyph cell — filling one
// `scale`x`scale` square per lit pixel. Sets ctx.fillStyle to `color`. Returns the
// x just past the string so callers can chain runs.
export function drawText(ctx, str, x, y, { scale = 2, color = '#F4F0E2', tracking = TRACKING } = {}) {
  ctx.fillStyle = color;
  const advance = (GLYPH_W + tracking) * scale;
  let penX = Math.round(x);
  const penY = Math.round(y);
  for (const ch of String(str)) {
    const px = glyphFor(ch);
    for (let i = 0; i < px.length; i++) {
      ctx.fillRect(penX + px[i][0] * scale, penY + px[i][1] * scale, scale, scale);
    }
    penX += advance;
  }
  return penX - tracking * scale;
}

// Render `str` to a fresh canvas sized to the text (+ optional padding), for DOM
// placement. Browser-only (needs document.createElement); tests exercise drawText.
export function renderToCanvas(str, { scale = 2, color = '#F4F0E2', tracking = TRACKING, pad = 0 } = {}) {
  const { width, height } = measure(str, { scale, tracking });
  const canvas = document.createElement('canvas');
  canvas.width = Math.max(1, width + pad * 2);
  canvas.height = height + pad * 2;
  const ctx = canvas.getContext('2d');
  ctx.imageSmoothingEnabled = false;
  drawText(ctx, str, pad, pad, { scale, color, tracking });
  return canvas;
}
