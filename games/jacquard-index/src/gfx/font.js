export const GLYPH_W = 5;
export const GLYPH_H = 7;

// Parse `#`/`.` rows into bit arrays once. `?` is the fallback for unknown chars.
const BITS = {};
for (const [ch, rows] of Object.entries(GLYPHS)) {
  BITS[ch] = rows.map((r) => r.split('').map((c) => (c === '#' ? 1 : 0)));
}

function glyphFor(ch) {
  const up = ch.toUpperCase();
  return BITS[up] || BITS['?'];
}

// Advance width of a string at the given scale + inter-glyph tracking (native px).
export function measureText(text, scale = 1, tracking = 1) {
  if (text.length === 0) return 0;
  const cell = (GLYPH_W + tracking) * scale;
  return text.length * cell - tracking * scale;
}

export const textHeight = (scale = 1) => GLYPH_H * scale;

// Draw `text` into `fb` with its top-left at (x, y). `color` is [r,g,b(,a)]. `scale`
// enlarges by integer blocks (native-res, nearest). Returns the advance width.
export function drawText(fb, x, y, text, color, scale = 1, tracking = 1) {
  const [r, g, b, a = 255] = color;
  let penX = x | 0;
  const step = (GLYPH_W + tracking) * scale;
  for (const ch of text) {
    const bits = glyphFor(ch);
    for (let gy = 0; gy < GLYPH_H; gy++) {
      const row = bits[gy];
      for (let gx = 0; gx < GLYPH_W; gx++) {
        if (!row[gx]) continue;
        if (scale === 1) {
          fb.setPixel(penX + gx, y + gy, r, g, b, a);
        } else {
          fb.fillRect(penX + gx * scale, y + gy * scale, scale, scale, r, g, b, a);
        }
      }
    }
    penX += step;
  }
  return penX - (x | 0) - tracking * scale;
}

// Convenience: draw horizontally centered within [x, x+width).
export function drawTextCentered(fb, x, width, y, text, color, scale = 1, tracking = 1) {
  const w = measureText(text, scale, tracking);
  return drawText(fb, x + Math.round((width - w) / 2), y, text, color, scale, tracking);
}
